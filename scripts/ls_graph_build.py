"""Generate the Clinical Study graph artifacts from src/clinical_study/graph_spec.py (one source, four outputs).

    .venv/bin/python -I scripts/ls_graph_build.py [--catalog eli_test_classic_catalog]

Outputs (committed; regenerate after any spec change, the parity test fails if they are stale):
  src/ontology/life_sciences/clinical_study.owl.ttl
  src/ontology/life_sciences/clinical_study.r2rml.ttl
  src/ontology/life_sciences/graph_views.sql          (${catalog} placeholder, applied by ls_apply_sql.py)
  docs/life_sciences/ONTOBRICKS_IMPORT.md
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from clinical_study import graph_spec as gs  # noqa: E402

OUT = ROOT / "src" / "ontology" / "life_sciences"
XSD = "http://www.w3.org/2001/XMLSchema#"


def snake(s: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", s).lower()


def entity_view(c: gs.Cls) -> str:
    return f"e_{snake(c.name)}"


def rel_view(prop: str, subj: str, obj: str) -> str:
    return f"r_{snake(prop)}__{snake(subj)}__{snake(obj)}"


def lit(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


# ------------------------------------------------------------------------------------------------ views
def views_sql() -> str:
    g = f"${{catalog}}.{gs.GRAPH_SCHEMA}"
    std = "${catalog}.clinical_study_standards"
    out = [
        "-- GENERATED by scripts/ls_graph_build.py from src/clinical_study/graph_spec.py. Do not edit by hand.",
        f"-- Ontobricks source scope = {gs.GRAPH_SCHEMA} only (no metric views, no gold answer tables).",
        "",
    ]
    out.append(f"""CREATE OR REPLACE VIEW {g}.kb_node COMMENT 'KB concepts with their single graph class.' AS
SELECT concept_id, scheme, code, notation, label, definition, concept_type, release,
       {gs.kb_class_case_sql()} AS graph_class,
       {gs.official_iri_sql()} AS official_iri,
       element_at(split(concept_type, ':'), 2) AS class_type,
       concept_type AS record_type
FROM {std}.kb_concept;
""")
    for c in gs.CLASSES:
        if c.sql is None and not c.attrs:
            continue  # abstract
        body = c.sql or (
            f"SELECT concept_id AS ID, label AS Label, code, scheme, release, definition, official_iri, "
            f"notation, class_type, record_type FROM {g}.kb_node WHERE graph_class = '{c.name}'"
        )
        out.append(
            f"CREATE OR REPLACE VIEW {g}.{entity_view(c)} COMMENT {lit('Entity source for ' + c.name)} AS\n"
            f"{body};\n"
        )
    for pred, s, o in gs.KB_RELS:
        p = gs.KB_PREDICATES[pred]
        out.append(f"""CREATE OR REPLACE VIEW {g}.{rel_view(p.name, s, o)} COMMENT {lit(f"{s} {p.name} {o} ({pred})")} AS
SELECT e.subject AS source_id, e.object AS target_id, e.authority, e.release
FROM {std}.kb_edge e
JOIN {g}.kb_node s ON s.concept_id = e.subject
JOIN {g}.kb_node o ON o.concept_id = e.object
WHERE e.predicate = '{pred}' AND s.graph_class = '{s}' AND o.graph_class = '{o}';
""")
    for r in gs.DATA_RELS:
        out.append(
            f"CREATE OR REPLACE VIEW {g}.{rel_view(r.prop, r.subject, r.object)} "
            f"COMMENT {lit(f'{r.subject} {r.prop} {r.object}')} AS\n{r.sql};\n"
        )
    return "\n".join(out)


# ------------------------------------------------------------------------------------------------ TBox
def all_rels() -> list[tuple[gs.Prop, str, str]]:
    return [(gs.KB_PREDICATES[p], s, o) for p, s, o in gs.KB_RELS] + [
        (gs.DATA_PROPS[r.prop], r.subject, r.object) for r in gs.DATA_RELS
    ]


def union(classes: list[str]) -> str:
    u = sorted(set(classes))
    if len(u) == 1:
        return f"<{gs.NS}#{u[0]}>"
    return "[ a owl:Class ; owl:unionOf ( " + " ".join(f"<{gs.NS}#{x}>" for x in u) + " ) ]"


def tbox() -> str:
    L = [
        "# GENERATED by scripts/ls_graph_build.py from src/clinical_study/graph_spec.py. Do not edit by hand.",
        "@prefix owl:  <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdf:  <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix xsd:  <http://www.w3.org/2001/XMLSchema#> .",
        f"@prefix cpl:  <{gs.NS}#> .",
        "",
        f"<{gs.NS}> a owl:Ontology ;",
        '    rdfs:label "Clinical Study Context & Evidence Lab ontology" ;',
        '    rdfs:comment "SYNTHETIC educational demo. Study-design classes are aligned in name with CDISC USDM; '
        "knowledge classes mirror MONDO, MED-RT, MeSH, RxNorm, CDISC CT and COSMoS. Relations are named in this "
        "namespace (Ontobricks compiles every property as <NS>/<name>); cpl:mirrorsPredicate records the official "
        "predicate a relation mirrors and cpl:source where it comes from. Nothing here is official CDISC "
        'content." ;',
        '    owl:versionInfo "1.0.0" .',
        "",
        "cpl:mirrorsPredicate a owl:AnnotationProperty .",
        "cpl:source a owl:AnnotationProperty .",
        "cpl:usdmAlignment a owl:AnnotationProperty .",
        "",
    ]
    for c in gs.CLASSES:
        L.append(
            f"<{gs.NS}#{c.name}> a owl:Class ; rdfs:label {lit(c.label)}"
            + (f" ;\n    rdfs:comment {lit(c.comment)}" if c.comment else "")
            + (f" ;\n    rdfs:subClassOf <{gs.NS}#{c.parent}>" if c.parent else "")
            + (f" ;\n    cpl:usdmAlignment {lit(c.usdm)}" if c.usdm else "")
            + " ."
        )
    L.append("")
    by_prop: dict[str, tuple[gs.Prop, list[str], list[str]]] = {}
    for p, s, o in all_rels():
        cur = by_prop.setdefault(p.name, (p, [], []))
        cur[1].append(s)
        cur[2].append(o)
    for name, (p, doms, rngs) in sorted(by_prop.items()):
        L.append(
            f"<{gs.NS}/{name}> a owl:ObjectProperty ; rdfs:label {lit(p.label)} ;"
            + (f"\n    rdfs:comment {lit(p.comment)} ;" if p.comment else "")
            + f"\n    rdfs:domain {union(doms)} ;\n    rdfs:range {union(rngs)} ;"
            + f"\n    cpl:source {lit(p.source)}"
            + (f" ;\n    cpl:mirrorsPredicate <{p.official}>" if p.official else "")
            + " ."
        )
    L.append("")
    attrs: dict[str, tuple[gs.Attr, list[str]]] = {}
    for c in gs.CLASSES:
        for a in c.attrs:
            attrs.setdefault(a.prop, (a, []))[1].append(c.name)
    for name, (a, doms) in sorted(attrs.items()):
        L.append(
            f"<{gs.NS}/{name}> a owl:DatatypeProperty ; rdfs:domain {union(doms)} ; rdfs:range xsd:{a.xsd}"
            + (f" ;\n    rdfs:comment {lit(a.comment)}" if a.comment else "")
            + " ."
        )
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------------------------------------ R2RML
def r2rml(catalog: str) -> str:
    g = f"{catalog}.{gs.GRAPH_SCHEMA}"
    L = [
        "# GENERATED by scripts/ls_graph_build.py from src/clinical_study/graph_spec.py. Do not edit by hand.",
        "@prefix rr:   <http://www.w3.org/ns/r2rml#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix xsd:  <http://www.w3.org/2001/XMLSchema#> .",
        f"@prefix map:  <{gs.NS}/mapping#> .",
        "",
    ]
    for c in gs.CLASSES:
        if c.sql is None and not c.attrs:
            continue
        v = entity_view(c)
        poms = ['    rr:predicateObjectMap [ rr:predicate rdfs:label ; rr:objectMap [ rr:column "Label" ] ]']
        for a in c.attrs:
            dt = "rr:termType rr:IRI" if a.xsd == "anyURI" else f"rr:datatype xsd:{a.xsd}"
            poms.append(
                f"    rr:predicateObjectMap [ rr:predicate <{gs.NS}/{a.prop}> ; "
                f'rr:objectMap [ rr:column "{a.column}" ; {dt} ] ]'
            )
        L.append(
            f'map:{v} a rr:TriplesMap ;\n    rr:logicalTable [ rr:tableName "{g}.{v}" ] ;\n'
            f'    rr:subjectMap [ rr:template "{gs.NS}/{c.name}/{{ID}}" ; rr:class <{gs.NS}#{c.name}> ] ;\n'
            + " ;\n".join(poms)
            + " .\n"
        )
    for p, s, o in all_rels():
        v = rel_view(p.name, s, o)
        L.append(
            f'map:{v} a rr:TriplesMap ;\n    rr:logicalTable [ rr:tableName "{g}.{v}" ] ;\n'
            f'    rr:subjectMap [ rr:template "{gs.NS}/{s}/{{source_id}}" ] ;\n'
            f"    rr:predicateObjectMap [ rr:predicate <{gs.NS}/{p.name}> ;\n"
            f'        rr:objectMap [ rr:template "{gs.NS}/{o}/{{target_id}}" ] ] .\n'
        )
    return "\n".join(L)


# ------------------------------------------------------------------------------------------------ checklist
def checklist(catalog: str) -> str:
    g = f"{catalog}.{gs.GRAPH_SCHEMA}"
    ents = [c for c in gs.CLASSES if c.sql is not None or c.attrs]
    rels = all_rels()
    L = [
        "# Ontobricks import — Clinical Study lab (GENERATED by scripts/ls_graph_build.py; do not edit)",
        "",
        f"Source scope: **`{g}` only**. It holds one view per class (`e_*`) and one per relationship (`r_*`). "
        "Don't add `clinical_study_semantic` (metric views abort the scan, as in HEDIS rev 5) or the gold "
        "eligibility/population tables (the graph has to derive those itself, ADR-0025).",
        "",
        f"IRI base: `{gs.NS}`. Class `{gs.NS}#<Class>`, property `{gs.NS}/<name>`, instance "
        f"`{gs.NS}/<Class>/<ID>`. This is the convention Ontobricks compiles, so the R2RML needs no prefix edits.",
        "",
        f"Counts: {len(ents)} classes with data, {len(rels)} relationship views, {len(set(p.name for p, _, _ in rels))} "
        "object properties.",
        "",
        "## Steps",
        "",
        "1. Create a new Ontobricks project/domain (suggested name **Clinical Study Lab**). Use a separate project, "
        "not `clinicaldomain`, so the HEDIS graph and its app pin are untouched.",
        "2. Import the ontology: `src/ontology/life_sciences/clinical_study.owl.ttl`.",
        "3. Import the mapping: `src/ontology/life_sciences/clinical_study.r2rml.ttl`. If the importer rewrites or "
        "rejects anything, fix it with the tables below. Each row is one view → one mapping, columns `ID`/`Label` "
        "for entities and `source_id`/`target_id` for relationships.",
        "4. Set source scope to the schema above, then build/publish.",
        "5. Send Claude the published triplestore table name (e.g. `eswanson_demo.ontobricks.triplestore_<project>_v1`). "
        "Claude runs the graph checks against it.",
        "",
        "## Entities",
        "",
        "| Class | View | Attributes |",
        "|---|---|---|",
    ]
    for c in ents:
        L.append(
            f"| `{c.name}` | `{entity_view(c)}` | {', '.join(f'{a.prop}←{a.column}' for a in c.attrs) or '—'} |"
        )
    L += ["", "## Relationships", "", "| Property | Source class → target class | View |", "|---|---|---|"]
    for p, s, o in rels:
        L.append(f"| `{p.name}` | {s} → {o} | `{rel_view(p.name, s, o)}` |")
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", default="eli_test_classic_catalog")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "graph_views.sql").write_text(views_sql())
    (OUT / "clinical_study.owl.ttl").write_text(tbox())
    (OUT / "clinical_study.r2rml.ttl").write_text(r2rml(a.catalog))
    (ROOT / "docs" / "life_sciences" / "ONTOBRICKS_IMPORT.md").write_text(checklist(a.catalog))
    print(f"classes={len(gs.CLASSES)} kb_rels={len(gs.KB_RELS)} data_rels={len(gs.DATA_RELS)}")


if __name__ == "__main__":
    main()
