"""Generate outside ophthalmology/optometry consult letters for a sample of real MY2026 EED-eligible patients.

Why: in a real health system, many diabetic eye exams happen at outside practices and arrive as letters or faxes
that never post as a structured result. They live only in unstructured documents, at a volume nobody curates into
Pages or maps into a graph; they are indexed and retrieved on demand (RAG, care-team access only). This makes that
real situation present in the demo, consistent with the data:

  - who: a fixed ~3% hash sample of MY2026 EED-eligible patients (abs(xxhash64(patient_id, 'outside_eye_2026')) % 100
    < 3). It does NOT look at EED gap status: some of these patients also had an in-system exam, some didn't.
  - when: an exam date in MY2026 on or before the extract horizon (2026-10-30), derived from the same hash.
  - what: findings follow the patient's own diagnoses (mild nonproliferative retinopathy if they carry E11.319,
    otherwise none); re-screening 12 months with retinopathy, 24 without.
  - names / DOB come from bronze_patient (Synthea's synthetic identities).

Writes docs/care_protocol/corpus/letters/LETTER-EYE-<id8>.md (committed; deterministic). Read-only on ECT.
Then reload the RAG corpus (RUNBOOK, A4) and re-run scripts/lakebase_grant_app_reader.py (a reload resets ACLs).

    .venv/bin/python -I scripts/gen_outside_letters.py
"""

from __future__ import annotations

import datetime as dt
import hashlib
import importlib.util
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/care_protocol/corpus/letters"
C = "eli_test_classic_catalog"
SAMPLE_PCT = 3
HORIZON = dt.date(2026, 10, 30)
PRACTICES = ["Community Eye Care Associates", "Valley Retina & Vision Center", "Northside Optometry Group"]
EXAMS = ["a dilated fundus examination of both eyes", "dilated retinal examination with fundus photography",
         "retinal imaging (non-mydriatic fundus photography) read by an ophthalmologist"]


def _q():
    spec = importlib.util.spec_from_file_location("q", ROOT / "scripts/q.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m.run


def _h(pid: str, salt: str) -> int:
    return int(hashlib.sha256(f"{pid}|{salt}".encode()).hexdigest(), 16)


def letter(r: dict) -> tuple[str, str]:
    pid = r["patient_id"]
    start = dt.date(2026, 1, 12)
    day = start + dt.timedelta(days=_h(pid, "date") % ((HORIZON - dt.timedelta(days=7) - start).days))
    practice, exam = PRACTICES[_h(pid, "practice") % 3], EXAMS[_h(pid, "exam") % 3]
    dr = r["retinopathy"] in (True, "true")
    finding = ("**Mild nonproliferative diabetic retinopathy** in both eyes, without macular edema" if dr
               else "**No evidence of diabetic retinopathy** in either eye")
    months = 12 if dr else 24
    doc_id = f"LETTER-EYE-{pid[:8]}"
    name = re.sub(r"\d+", "", f"{r['first_name']} {r['last_name']}")  # Synthea suffixes names with digits
    body = f"""---
doc_id: {doc_id}
title: "Outside Eye Exam Letter — {name} ({day.isoformat()})"
source: "Synthetic outside-provider correspondence generated by scripts/gen_outside_letters.py for a real demo patient. No real PHI."
license: synthetic
effective_date: {day.isoformat()}
measurement_year: 2026
access: [care_team]
patient_id: {pid}
labels: "Synthetic · Patient-specific · Restricted (care team) · Not for clinical use"
---

# {practice} — Consultation Letter

**Re:** {name} · DOB {r['birth_date']} · patient {pid}
**Date of service:** {day.isoformat()} · **To:** the patient's primary care clinic ({r['clinic_id']})

> Synthetic patient-specific correspondence for the Care Protocol demo. No real PHI. Care-team access only.

## Examination

The patient, who has diabetes, was seen for a diabetic eye examination. We performed {exam}.

## Findings

{finding}.

## Plan

- Diabetic retinal examination completed on {day.isoformat()}.
- Recommend re-screening in **{months} months**{' and follow-up with your diabetes team on glycemic and blood-pressure control' if dr else ''}.

This examination was performed at an outside practice and is being sent by letter; it will not appear as a
structured result in your EHR unless it is abstracted.
"""
    return doc_id, body


def main() -> None:
    run = _q()
    rows = run(f"""
        WITH dr AS (SELECT DISTINCT patient_id FROM {C}.care_protocol.silver_condition
                    WHERE icd10_code = 'E11.319' AND onset_date <= DATE'2026-10-30')
        SELECT e.patient_id, e.clinic_id, p.first_name, p.last_name, CAST(p.birth_date AS STRING) AS birth_date,
               dr.patient_id IS NOT NULL AS retinopathy
        FROM {C}.care_protocol.gold_adherence_eed e
        JOIN {C}.care_protocol.bronze_patient p USING (patient_id)
        LEFT JOIN dr USING (patient_id)
        WHERE e.measurement_year = 2026 AND abs(xxhash64(e.patient_id, 'outside_eye_2026')) % 100 < {SAMPLE_PCT}
        ORDER BY e.patient_id""")
    OUT.mkdir(parents=True, exist_ok=True)
    keep = set()
    for r in rows:
        doc_id, body = letter(r)
        (OUT / f"{doc_id}.md").write_text(body, encoding="utf-8")
        keep.add(f"{doc_id}.md")
    for old in OUT.glob("LETTER-EYE-*.md"):  # only files this script wrote, no longer in the sample
        if old.name not in keep:
            old.unlink()
    print(f"wrote {len(keep)} letters to {OUT.relative_to(ROOT)} ({sum(r['retinopathy'] in (True, 'true') for r in rows)} with retinopathy)")


if __name__ == "__main__":
    main()
