"""Add the semantic half of the A4 hybrid retriever: embed each corpus doc with pgvector.

Computes a gte-large-en embedding (1024-dim) for each Genie Ontology Page and emits Postgres SQL (to stdout)
that installs pgvector, adds an `embedding` column to retrieval_corpus, UPDATEs each row, and builds an HNSW
cosine index. Pipe into Lakebase AFTER scripts/lakebase_corpus.py has created/loaded the table:

    python scripts/lakebase_embed.py --src_dir docs/ontology/pages --profile ECT | \
      PGPASSWORD="$TOKEN" psql "host=$HOST user=$USER dbname=databricks_postgres sslmode=require"

Reproducible-by-code: embeddings are derived from the version-controlled Pages via a governed endpoint.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lakebase_corpus import parse_md  # noqa: E402

EMBED_ENDPOINT = "databricks-gte-large-en"


def embed(w, text):
    r = w.serving_endpoints.query(name=EMBED_ENDPOINT, input=[text])
    if getattr(r, "data", None):
        return r.data[0].embedding
    return r.predictions[0]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src_dir", default="docs/ontology/pages")
    ap.add_argument("--profile", default=None)
    args = ap.parse_args()

    from databricks.sdk import WorkspaceClient
    import glob
    w = WorkspaceClient(profile=args.profile) if args.profile else WorkspaceClient()

    updates, dim = [], None
    for path in sorted(glob.glob(os.path.join(args.src_dir, "*.md"))):
        if os.path.basename(path).lower() == "readme.md":
            continue
        doc_id, title, synonyms, body = parse_md(path)
        vec = embed(w, f"{title} {synonyms} {body}")
        dim = dim or len(vec)
        lit = "[" + ",".join(f"{x:.6f}" for x in vec) + "]"
        updates.append(f"UPDATE retrieval_corpus SET embedding = '{lit}'::vector WHERE doc_id = '{doc_id}';")

    print("-- A4 pgvector semantic half (generated by lakebase_embed.py)")
    print("CREATE EXTENSION IF NOT EXISTS vector;")
    print(f"ALTER TABLE retrieval_corpus ADD COLUMN IF NOT EXISTS embedding vector({dim});")
    print("\n".join(updates))
    print("CREATE INDEX IF NOT EXISTS idx_corpus_vec ON retrieval_corpus "
          "USING hnsw (embedding vector_cosine_ops);")
    print("SELECT count(embedding) AS embedded_docs FROM retrieval_corpus;")


if __name__ == "__main__":
    main()
